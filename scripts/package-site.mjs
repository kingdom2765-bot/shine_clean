import { readFile, writeFile, mkdir, copyFile, readdir, cp, unlink } from 'node:fs/promises';
import { build } from './build.mjs';
import { siteBase } from './seo.mjs';

const root = new URL('../', import.meta.url);
const config = JSON.parse(await readFile(new URL('site.config.json', root), 'utf8'));
const base = siteBase(process.env.SITE_URL || config.siteUrl);
if (!base && !process.argv.includes('--preview')) throw new Error('배포 전 site.config.json의 siteUrl 또는 SITE_URL에 정식 HTTPS 주소를 설정해 주세요.');
const pages = await build();
const output = new URL('_site/', root); await mkdir(output, { recursive: true });
const assets = ['motion.css', 'motion.js', 'styles.css', 'design-tokens.css', 'work.css', 'estimate.css', 'admin.css', 'app.js', 'work.js', 'estimate.js', 'admin.js', 'admin-model.js', 'client-records.js', 'client-model.js', 'public-client-model.js', 'firebase-client.js'];
const files = [...pages, ...assets, 'robots.txt', ...(base ? ['sitemap.xml'] : [])];
for (const name of files) await copyFile(new URL(name, root), new URL(name, output));
// Only remove obsolete pagination and sitemap files generated by this packager.
for (const name of await readdir(output)) if ((/^p3-our-work-page-[0-9]+\.html$/.test(name) || name === 'sitemap.xml') && !files.includes(name)) await unlink(new URL(name, output));
await cp(new URL('assets/', root), new URL('assets/', output), { recursive: true });
await writeFile(new URL('.nojekyll', output), '');
console.log(`Prepared _site/ (${pages.length} pages). Deploy this directory; source, raw data and backups are excluded.`);
